--3
SELECT a.NUME, a.TARA_ORIGINE, COUNT(v.ID_VANZARE) AS NR_VANZARI, SUM(v.PRET_FINAL) AS TOTAL_INCASARI
FROM ARTISTI_PRJ a

JOIN LUCRARI_ARTA_PRJ l ON a.ID_ARTIST = l.ID_ARTIST JOIN VANZARI_PRJ v ON l.ID_LUCRARE = v.ID_LUCRARE GROUP BY a.NUME, a.TARA_ORIGINE
ORDER BY TOTAL_INCASARI DESC;

--4
SELECT c.NUME AS NUME_CLIENT, COUNT(v.ID_VANZARE) AS NR_TRANZACTII, SUM(v.PRET_FINAL) AS TOTAL_2022
FROM CLIENTI_PRJ c

JOIN VANZARI_PRJ v ON c.ID_CLIENT = v.ID_CLIENT WHERE EXTRACT(YEAR FROM v.DATA_VANZARE) = 2022 GROUP BY c.NUME
ORDER BY TOTAL_2022 DESC;
--5
SELECT e.NUME AS NUME_EXPOZITIE, e.LOCATIE, COUNT(DISTINCT l.ID_ARTIST) AS NR_ARTISTI_DISTINCTI
FROM EXPOZITII_PRJ e

JOIN LUCRARI_EXPOZITII_PRJ le ON e.ID_EXPOZITIE = le.ID_EXPOZITIE JOIN LUCRARI_ARTA_PRJ l ON le.ID_LUCRARE = l.ID_LUCRARE
GROUP BY e.NUME, e.LOCATIE

ORDER BY NR_ARTISTI_DISTINCTI DESC;
